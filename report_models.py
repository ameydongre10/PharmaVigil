"""
Report and evaluation data schemas for Phase 5 End-to-End PADER Assembly.
"""

from pydantic import BaseModel, Field
from typing import List, Dict, Any, Optional
from datetime import datetime, timezone
from enum import Enum


class SectionType(str, Enum):
    DETERMINISTIC = "deterministic"
    LLM_GENERATED = "llm_generated"
    LIMITATION_STATEMENT = "limitation_statement"


class SectionStatus(str, Enum):
    PASS = "PASS"
    REVIEW_REQUIRED = "REVIEW_REQUIRED"
    FAILED = "FAILED"
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"


class ReportStatus(str, Enum):
    DRAFT_PENDING_REVIEW = "DRAFT_PENDING_REVIEW"
    HUMAN_APPROVED = "HUMAN_APPROVED"
    NEEDS_REVISION = "NEEDS_REVISION"
    REJECTED = "REJECTED"
    SIMULATED_APPROVED = "SIMULATED_APPROVED"


class ReviewDecision(str, Enum):
    PENDING_REVIEW = "PENDING_REVIEW"
    APPROVED = "APPROVED"
    NEEDS_REVISION = "NEEDS_REVISION"
    REJECTED = "REJECTED"
    SIMULATED_APPROVED = "SIMULATED_APPROVED"


class SectionOutput(BaseModel):
    """Encapsulates the rendered output of a single report section."""
    section_name: str
    section_type: SectionType
    is_required_by_assignment: bool = True
    narrative: Optional[str] = None
    structured_tables: Optional[Dict[str, Any]] = None
    evidence_ids: List[str] = Field(default_factory=list)
    limitations: List[str] = Field(default_factory=list)
    validation_status: SectionStatus = Field(default=SectionStatus.PASS)
    validation_warnings: List[str] = Field(default_factory=list)
    generation_metadata: Optional[Dict[str, Any]] = None


class ReportMetadata(BaseModel):
    """Metadata describing the PADER report header."""
    report_type: str = "PADER"
    product_name: str = "BISOPROLOL"
    application_number: str = "B-1"
    sponsor_name: str = "Dev Pharma Client"
    reporting_period_start: str
    reporting_period_end: str
    generated_at_utc: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    version: str = "1.0.0 (V0 Prototype)"


class EvaluationReport(BaseModel):
    """Machine-readable quality evaluation results for the assembled report."""
    report_id: str
    timestamp_utc: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    total_sections: int
    required_sections_total: int
    required_sections_present: int
    required_sections_complete: bool
    additional_limitation_sections_present: List[str] = Field(default_factory=list)
    generated_sections: int
    deterministic_sections: int
    passed_validation_sections: int
    failed_validation_sections: int
    factual_consistency_score: float = Field(..., description="Percentage of verified numbers matching evidence (0-100)")
    grounding_score: float = Field(..., description="Percentage of sections referencing valid evidence IDs (0-100)")
    unsupported_claim_count: int
    automated_evaluation_status: SectionStatus = Field(..., description="Automated check status: PASS or REVIEW_REQUIRED")
    is_human_approved: bool = Field(default=False, description="Explicit human approval flag (separate from automated eval)")
    section_details: Dict[str, Dict[str, Any]]


class ReviewRecord(BaseModel):
    """Audit record capturing human review decision and feedback."""
    report_id: str
    reviewed_at_utc: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    reviewer_decision: ReviewDecision
    reviewer_name: str = "Qualified Safety Reviewer"
    is_simulated: bool = Field(default=False, description="True if generated by an automated test/demo fixture")
    section_statuses: Dict[str, SectionStatus]
    reviewer_notes: Optional[str] = None


class PADERReport(BaseModel):
    """Top-level object representing an assembled PADER-style regulatory report."""
    metadata: ReportMetadata
    sections: List[SectionOutput]
    status: ReportStatus = Field(default=ReportStatus.DRAFT_PENDING_REVIEW)
    review_record: Optional[ReviewRecord] = None
    evaluation: Optional[EvaluationReport] = None
